-- 1. Enable pgcrypto extension for data encryption & decryption
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 2. ENABLE ROW LEVEL SECURITY (RLS) ON ORDERS TABLE
ALTER TABLE IF EXISTS orders ENABLE ROW LEVEL SECURITY;

-- Allow public / anon users to INSERT orders (needed during checkout)
DROP POLICY IF EXISTS "Allow anonymous insert orders" ON orders;
CREATE POLICY "Allow anonymous insert orders" 
  ON orders 
  FOR INSERT 
  TO anon, authenticated 
  WITH CHECK (true);

-- Deny public / anon users from SELECTING orders
-- Only backend service_role key can read all customer orders
DROP POLICY IF EXISTS "Allow service_role full access on orders" ON orders;
CREATE POLICY "Allow service_role full access on orders" 
  ON orders 
  FOR ALL 
  TO service_role 
  USING (true) 
  WITH CHECK (true);

-- 3. ENABLE ROW LEVEL SECURITY (RLS) ON COUPONS TABLE
CREATE TABLE IF NOT EXISTS coupons (
  id bigint PRIMARY KEY,
  code text NOT NULL UNIQUE,
  percent integer NOT NULL DEFAULT 0,
  "waivesShipping" boolean NOT NULL DEFAULT false,
  enabled boolean NOT NULL DEFAULT true
);

ALTER TABLE coupons ENABLE ROW LEVEL SECURITY;

-- Allow anonymous users to READ ONLY active coupons
DROP POLICY IF EXISTS "Allow public read active coupons" ON coupons;
CREATE POLICY "Allow public read active coupons" 
  ON coupons 
  FOR SELECT 
  TO anon, authenticated 
  USING (enabled = true);

-- Allow service_role key full CRUD on coupons
DROP POLICY IF EXISTS "Allow service_role full access on coupons" ON coupons;
CREATE POLICY "Allow service_role full access on coupons" 
  ON coupons 
  FOR ALL 
  TO service_role 
  USING (true) 
  WITH CHECK (true);

-- 4. ENABLE ROW LEVEL SECURITY (RLS) ON SHOP_SETTINGS TABLE
-- products and faqs JSON columns are the shared catalog used by the admin dashboard.
CREATE TABLE IF NOT EXISTS shop_settings (
  id int PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  manual_override text DEFAULT NULL,
  products jsonb DEFAULT NULL,
  faqs jsonb DEFAULT NULL,
  flash_sale boolean NOT NULL DEFAULT false,
  coupon_hint_enabled boolean NOT NULL DEFAULT true,
  coupon_hint_code text NOT NULL DEFAULT 'SHIPPING'
);

ALTER TABLE shop_settings ADD COLUMN IF NOT EXISTS products jsonb DEFAULT NULL;
ALTER TABLE shop_settings ADD COLUMN IF NOT EXISTS faqs jsonb DEFAULT NULL;
ALTER TABLE shop_settings ADD COLUMN IF NOT EXISTS flash_sale boolean NOT NULL DEFAULT false;
ALTER TABLE shop_settings ADD COLUMN IF NOT EXISTS coupon_hint_enabled boolean NOT NULL DEFAULT true;
ALTER TABLE shop_settings ADD COLUMN IF NOT EXISTS coupon_hint_code text NOT NULL DEFAULT 'SHIPPING';

INSERT INTO shop_settings (id, manual_override) VALUES (1, NULL)
  ON CONFLICT (id) DO NOTHING;

ALTER TABLE shop_settings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read shop_settings" ON shop_settings;
CREATE POLICY "Allow public read shop_settings"
  ON shop_settings FOR SELECT TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow service_role write shop_settings" ON shop_settings;
CREATE POLICY "Allow service_role write shop_settings"
  ON shop_settings FOR ALL TO service_role
  USING (true) WITH CHECK (true);

-- 5. ENABLE ROW LEVEL SECURITY (RLS) ON ITEM_REQUESTS TABLE
CREATE TABLE IF NOT EXISTS item_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text DEFAULT 'Anonymous',
  item text NOT NULL,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE item_requests ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow anonymous insert item_requests" ON item_requests;
CREATE POLICY "Allow anonymous insert item_requests"
  ON item_requests FOR INSERT TO anon, authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Allow service_role full access item_requests" ON item_requests;
CREATE POLICY "Allow service_role full access item_requests"
  ON item_requests FOR ALL TO service_role
  USING (true) WITH CHECK (true);

